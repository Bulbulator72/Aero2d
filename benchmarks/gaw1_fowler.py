def _spl(xt, zt):
    """Сплайн по u = sqrt(x) (у носка z ~ sqrt(x)); табличные ординаты
    кусочно-линейной интерполяцией дают изломы и «пилу» скорости."""
    from scipy.interpolate import make_interp_spline
    s = make_interp_spline(np.sqrt(xt), zt, k=3)
    return lambda x: s(np.sqrt(np.clip(x, 0, None)))


def _sspl(xt, zt, lam):
    """Сглаживающий сплайн (ординаты закрылка в таблице с заметным шумом)."""
    from scipy.interpolate import make_smoothing_spline
    s = make_smoothing_spline(np.sqrt(xt), zt, lam=lam)
    return lambda x: s(np.sqrt(np.clip(x, 0, None)))


_SU, _SL = _spl(_X, _ZU), _spl(_X, _ZL)
_FSU, _FSL = _sspl(_FXU, _FZU, 2e-6), _sspl(_FXL, _FZL, 2e-6)


def _interp_upper(x):
    return _SU(x)


def _interp_lower(x):
    return _SL(x)


def flap_nested():
    """Контур закрылка в убранном положении (обход ЗК → верх → носок → низ → ЗК)."""
    t = (1 - np.cos(np.linspace(0, np.pi, 80))) / 2 * _FXU[-1]
    zu, zl = _FSU(t), _FSL(t)
    # толщина задней кромки (0.7 % c) убирается за счёт нижней (наветренной)
    # поверхности, плавно по всей хорде: верх закрылка, где развивается
    # отрыв, не искажается
    dz = zu[-1] - zl[-1]
    import os
    mode = os.environ.get("FLAP_TE", "lower")
    if mode == "lower":
        zl = zl + dz * (t / t[-1]) ** 2
    else:                                    # симметрично на последних 10 %
        w = np.clip((t - 0.9 * t[-1]) / (0.1 * t[-1]), 0, 1) ** 2
        zu, zl = zu - 0.5 * dz * w, zl + 0.5 * dz * w
    xu, xl = t + FLAP_X0, t + FLAP_X0
    x = np.concatenate([xu[::-1], xl[1:]])
    z = np.concatenate([zu[::-1], zl[1:]])
    return x, z


def main_element(n_le=60, fair=True):
    """Основной элемент: верх профиля до x = 0.96 (кромка козырька), низ
    профиля до угла ниши (~0.725). fair=True — ниша закрыта «обтекателем»
    (кубика Эрмита от угла ниши к кромке козырька, по касательным): в
    реальном течении ниша занята застойной зоной, граница которой идёт
    примерно так же (так делают и в MSES-подобных расчётах). fair=False —
    ниша повторяет верх убранного закрылка с зазором 0.002c."""
    from aero2d.geometry import Airfoil
    xs = (1 - np.cos(np.linspace(0, np.pi, 2 * n_le))) / 2 * MAIN_TE_X
    upper = np.column_stack([xs, _interp_upper(xs)])
    zte_u = _interp_upper(MAIN_TE_X)
    x_cove0 = 0.725
    xl = (1 - np.cos(np.linspace(0, np.pi, 2 * n_le))) / 2 * x_cove0
    lower = np.column_stack([xl, _interp_lower(xl)])
    p0 = lower[-1]
    p1 = np.array([MAIN_TE_X, zte_u - 0.0006])        # конечная толщина кромки козырька
    if fair:
        t0 = np.array([1.0, (_interp_lower(x_cove0) - _interp_lower(x_cove0 - 0.01)) / 0.01])
        sl = (_FSU(MAIN_TE_X - FLAP_X0) - _FSU(MAIN_TE_X - FLAP_X0 - 0.01)) / 0.01
        t1 = np.array([1.0, sl])
        L = np.hypot(*(p1 - p0))
        t0, t1 = t0 / np.hypot(*t0) * L, t1 / np.hypot(*t1) * L
        s = np.linspace(0, 1, 40)[1:]
        h00, h10, h01, h11 = 2*s**3 - 3*s**2 + 1, s**3 - 2*s**2 + s, -2*s**3 + 3*s**2, s**3 - s**2
        cove = h00[:, None] * p0 + h10[:, None] * t0 + h01[:, None] * p1 + h11[:, None] * t1
        pts = np.vstack([upper[::-1], lower[1:], cove])
    else:
        xc = np.linspace(FLAP_X0 + 0.028, MAIN_TE_X, 40)
        zc = np.interp(xc - FLAP_X0, _FXU, _FZU) + 0.002
        zc[-1] = p1[1]
        p1c = np.array([xc[0], zc[0]])
        s = np.linspace(0, 1, 10)[1:-1]
        bez_c = np.array([p0[0] + 0.004, p1c[1] - 0.004])
        arc = ((1 - s) ** 2)[:, None] * p0 + (2 * s * (1 - s))[:, None] * bez_c + (s ** 2)[:, None] * p1c
        pts = np.vstack([upper[::-1], lower[1:], arc, np.column_stack([xc, zc])])
    return Airfoil(pts[:, 0], pts[:, 1], "GA(W)-1 main")


def flap(deflection):
    """Закрылок, отклонённый на deflection (°) по таблице осей рис. 3."""
    from aero2d.geometry import Airfoil
    x, z = flap_nested()
    px, pz = PIVOT_NESTED
    nx, nz = PIVOTS[deflection]
    d = np.radians(-deflection)                      # отклонение вниз — поворот по часовой
    c, s = np.cos(d), np.sin(d)
    xr = px + (x - px) * c - (z - pz) * s
    zr = pz + (x - px) * s + (z - pz) * c
    return Airfoil(xr - px + nx, zr - pz + nz, f"Fowler 29% {deflection}°")


def configuration(deflection, n_main=140, n_flap=70, fair=True):
    from aero2d.geometry import repanel
    m = repanel(main_element(fair=fair), n_main, keep_frame=True)
    f = repanel(flap(deflection), n_flap, keep_frame=True)
    return [m, f]


def gap_overlap(deflection):
    """Щель (мин. расстояние от кромки козырька до закрылка) и перекрытие
    (x кромки козырька − x носка закрылка), в долях хорды."""
    m = main_element()
    f = flap(deflection)
    te = np.array([m.x[0], m.y[0]])
    d = np.hypot(f.x - te[0], f.y - te[1])
    return float(d.min()), float(te[0] - f.x.min())
